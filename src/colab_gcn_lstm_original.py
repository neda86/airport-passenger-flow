def test_train_split(demands, targets, Batch=16, train_ratio=0.80, val_ratio=0.05): # 15% test , Batch starts from 8, 16, 32, 64,...
    total = demands.shape[0] # total number of data points
    train_end = int(total * train_ratio)
    val_end = train_end + int(total * val_ratio)

    X_train, y_train = demands[:train_end], targets[:train_end]
    X_val, y_val = demands[train_end:val_end], targets[train_end:val_end]
    X_test, y_test = demands[val_end:], targets[val_end:]

    train_ds = TensorDataset(torch.tensor(X_train, dtype=torch.float32),
                             torch.tensor(y_train, dtype=torch.float32))
    val_ds   = TensorDataset(torch.tensor(X_val, dtype=torch.float32),
                             torch.tensor(y_val, dtype=torch.float32))
    test_ds  = TensorDataset(torch.tensor(X_test, dtype=torch.float32),
                             torch.tensor(y_test, dtype=torch.float32))

    train_loader = DataLoader(train_ds, batch_size=Batch, shuffle=True, drop_last=True)
    val_loader   = DataLoader(val_ds, batch_size=Batch, shuffle=False, drop_last=False)
    test_loader  = DataLoader(test_ds, batch_size=Batch, shuffle=False, drop_last=False)

    return train_loader, val_loader, test_loader

