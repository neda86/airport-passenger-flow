class GraphConvolution(nn.Module):
    def __init__(self, in_features, out_features):
        super(GraphConvolution, self).__init__()
        self.linear = nn.Linear(in_features, out_features)

    def forward(self, x, adj):
        # x: (B, N, F)
        # adj: (N, N) --> expand to (B, N, N)
        if adj.dim() == 2:
            adj = adj.unsqueeze(0).repeat(x.size(0), 1, 1)  # (B, N, N)

        support = self.linear(x)  # (B, N, out_features)
        output = torch.bmm(adj, support)  # (B, N, out_features)
        return F.relu(output)

class GCN_LSTM(nn.Module):
    def __init__(self, A, in_features, out_features, num_nodes, hidden_size, num_layers, batch_size, p):
        super(GCN_LSTM, self).__init__()

        self.A = A  # Adjacency matrix (torch.Tensor N×N)
        self.in_features = in_features
        self.out_features = out_features
        self.num_nodes = num_nodes
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.batch_size = batch_size
        self.dropout = p

        self.gcn = GraphConvolution(in_features, hidden_size)

        self.lstm = nn.LSTM(
            input_size=num_nodes * hidden_size,
            hidden_size=hidden_size * out_features,
            num_layers=num_layers,
            batch_first=True,
            dropout=p
        )

        self.fc = nn.Linear(hidden_size * out_features, num_nodes * out_features)

    def init_hidden(self,batch_size,device):
        h0 = torch.zeros(self.num_layers, batch_size, self.hidden_size * self.out_features).to(device)
        c0 = torch.zeros(self.num_layers, batch_size, self.hidden_size * self.out_features).to(device)
        return h0, c0

    def forward(self, x):
        B, N, F, T = x.shape
        A = self.A.to(x.device)

        gcn_out_seq = []
        for t in range(T):
            x_t = x[:, :, :, t]  # (B, N, F)
            gcn_out = self.gcn(x_t, A)  # (B, N, hidden_size)
            gcn_out_seq.append(gcn_out)

        gcn_seq = torch.stack(gcn_out_seq, dim=1)  # (B, T, N, hidden_size)
        gcn_seq = gcn_seq.reshape(B, T, -1)        # (B, T, N * hidden_size)

        h0, c0 = self.init_hidden(B, x.device)      # Use the actual batch size B
        lstm_out, _ = self.lstm(gcn_seq, (h0, c0))
        last_out = lstm_out[:, -1, :]              # (B, hidden_size * out_features)

        out = self.fc(torch.tanh(last_out))        # (B, N * out_features)
        out = out.view(B, self.num_nodes, self.out_features)  # (B, N, out_features)
        return out

def TrainModel(model, train_dataloader, valid_dataloader, learning_rate=1e-5, num_epochs=300):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)

    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=learning_rate)

    losses_train = []
    losses_valid = []
    losses_epochs_train = []
    losses_epochs_valid = []

    for epoch in range(num_epochs):
        model.train()
        epoch_train_loss = 0

        for x_batch, y_batch in train_dataloader:
            x_batch, y_batch = x_batch.to(device), y_batch.to(device)

            optimizer.zero_grad()
            y_pred = model(x_batch)
            loss = criterion(y_pred, y_batch)
            loss.backward()
            optimizer.step()

            epoch_train_loss += loss.item()

        avg_train_loss = epoch_train_loss / len(train_dataloader)
        losses_train.append(avg_train_loss)
        losses_epochs_train.append(epoch)

        model.eval()
        epoch_val_loss = 0
        with torch.no_grad():
            for x_batch, y_batch in valid_dataloader:
                x_batch, y_batch = x_batch.to(device), y_batch.to(device)
                y_pred = model(x_batch)
                loss = criterion(y_pred, y_batch)
                epoch_val_loss += loss.item()

        avg_val_loss = epoch_val_loss / len(valid_dataloader)
        losses_valid.append(avg_val_loss)
        losses_epochs_valid.append(epoch)

        print(f"Epoch [{epoch+1}/{num_epochs}], Train Loss: {avg_train_loss:.10f}, Val Loss: {avg_val_loss:.10f}")

    # Plot training and validation loss
    plt.figure(figsize=(8, 5))
    plt.plot(losses_epochs_train, losses_train, label='Train Loss', marker='o')
    plt.plot(losses_epochs_valid, losses_valid, label='Validation Loss', marker='x')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.title('Training & Validation Loss over Epochs')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()
    plt.savefig('/content/drive/MyDrive/airport_p/train_val_loss_plot.png', dpi=300)


    return model, [losses_train, losses_valid, losses_epochs_train, losses_epochs_valid]

def TestModel(model, test_dataloader):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    model.eval()

    l1_loss = nn.L1Loss()
    mse_loss = nn.MSELoss()

    labels_list = []
    output_result = []
    losses_l1 = []
    losses_mse = []

    with torch.no_grad():
        for x_batch, y_batch in test_dataloader:
            x_batch, y_batch = x_batch.to(device), y_batch.to(device)

            y_pred = model(x_batch)

            labels_list.append(y_batch.cpu().numpy())
            output_result.append(y_pred.cpu().numpy())

            losses_l1.append(l1_loss(y_pred, y_batch).item())
            losses_mse.append(mse_loss(y_pred, y_batch).item())

    mean_l1 = np.mean(losses_l1)
    std_l1 = np.std(losses_l1)
    RMSE = np.sqrt(np.mean(losses_mse))

    return [
        np.concatenate(labels_list, axis=0),np.concatenate(output_result, axis=0),losses_l1, losses_mse, mean_l1, std_l1, RMSE
        ]

